/// The real JSON the server produces (generated by web/test/fixtures.test.ts).
dynamic fixture(String name) => jsonDecode(File('../web/test/fixtures/$name.json').readAsStringSync());

/// A request the fake server saw.
class Seen {
  Seen(this.method, this.path, this.query, this.body);
  final String method;
  final String path;
  final Map<String, String> query;
  final String body;
  @override
  String toString() => '$method $path ${query.isEmpty ? '' : query}';
}

typedef Reply = http.Response Function(http.Request req);

/// A fake server: answers from fixtures by default, records every request, and lets a test override any route.
class FakeServer {
  FakeServer({Map<String, Reply>? overrides}) : _overrides = overrides ?? {};
  final Map<String, Reply> _overrides;
  final List<Seen> seen = [];

  static http.Response json(Object? body, [int status = 200]) => http.Response(jsonEncode(body), status, headers: {'content-type': 'application/json'});
  static http.Response error(int status, String code, String message) => json({'error': {'code': code, 'message': message}}, status);

  MockClient get client => MockClient((req) async {
        final path = req.url.path.replaceFirst('/api/v1', '');
        seen.add(Seen(req.method, path, req.url.queryParameters, req.body));
        final key = '${req.method} $path';
        final custom = _overrides[key];
        if (custom != null) return custom(req);
        return _default(req, path);
      });

  http.Response _default(http.Request req, String path) {
    switch ('${req.method} $path') {
      case 'GET /tasks':
        return json(fixture('day-view'));
      case 'GET /labels':
        return json(fixture('labels'));
      case 'GET /settings':
        return json(fixture('settings'));
      case 'GET /stats':
        return json(fixture('stats'));
      case 'GET /habits':
        return json(fixture('habits'));
      case 'GET /sheet':
        return json(fixture('sheet'));
      case 'GET /review':
        return json(fixture('review'));
      case 'GET /activity':
        return json(fixture('activity'));
      case 'GET /search':
        return json(fixture('search'));
      case 'GET /me':
        return json({'id': 'user-1', 'email': 'me@example.com', 'timezone': 'UTC', 'ai_access_id': 'x' * 43, 'ai_access_enabled': true, 'ai_last_used_at': null});
    }
    if (req.method == 'DELETE') return json({'ok': true});

    final sent = req.body.isEmpty ? <String, dynamic>{} : jsonDecode(req.body) as Map<String, dynamic>;
    final seg = path.split('/').where((s) => s.isNotEmpty).toList(); // e.g. [tasks, id, days, 2026-11-06]
    if (req.method == 'POST' && path == '/tasks') return json(_task(sent['id'] as String?, sent), 201);
    if (req.method == 'POST' && path == '/tasks/move') return json({'moved': sent['ids']});
    if (req.method == 'POST' && path.endsWith('/restore')) return json(_task(seg[1], const {}));
    if (req.method == 'PATCH' && seg.length == 2 && seg[0] == 'tasks') return json(_task(seg[1], sent));
    if (req.method == 'PUT' && seg.length == 4 && seg[2] == 'days') return json(_task(seg[1], {'status': sent['status'], 'day_note': sent['note']}));
    if (req.method == 'PUT' && seg.length == 3 && seg[0] == 'days' && seg[2] == 'top') return json(fixture('day-view'));
    if (req.method == 'PATCH' && path == '/settings') return json({...(fixture('settings') as Map<String, dynamic>), ...sent});
    if (req.method == 'PATCH' && seg.length == 2 && seg[0] == 'labels') {
      final all = [...(fixture('labels')['types'] as List), ...(fixture('labels')['priorities'] as List)].cast<Map<String, dynamic>>();
      return json({...all.firstWhere((l) => l['id'] == seg[1], orElse: () => all.first), ...sent});
    }
    if (req.method == 'POST' && path == '/me/password') return json({'ok': true});
    return error(404, 'not_found', 'No fake route for ${req.method} $path');
  }

  /// What the server would return for a task: the fixture task with this id (or the first one) plus the changes.
  Map<String, dynamic> _task(String? id, Map<String, dynamic> changes) {
    final tasks = (fixture('day-view')['tasks'] as List).cast<Map<String, dynamic>>();
    final base = tasks.firstWhere((t) => t['id'] == id, orElse: () => tasks.first);
    return {...base, if (id != null) 'id': id, ...changes};
  }

  Iterable<Seen> where(String method, String path) => seen.where((s) => s.method == method && s.path == path);
}

/// A native layer that does nothing, except pretend to be signed in.
class FakeBridge extends PlatformBridge {
  FakeBridge({this.status = const SyncStatus(signedIn: true)}) : super(const MethodChannel('test/ignored'));
  final SyncStatus status;
  int syncRequests = 0;

  /// What the widget's "+" left behind; reading it consumes it, like the native side.
  String? pendingLaunchAction;
  @override
  Future<String?> launchAction() async {
    final a = pendingLaunchAction;
    pendingLaunchAction = null;
    return a;
  }

  @override
  Future<({String baseUrl, String token})?> getSession() async => (baseUrl: 'https://test', token: 'tok');
  @override
  Future<void> requestSync() async => syncRequests++;
  @override
  Future<String?> timeZone() async => 'UTC';
  @override
  Future<SyncStatus> syncStatus() async => status;
  @override
  Future<Permissions> permissions() async => const Permissions();
  @override
  Future<SyncResult> syncNow() async => const SyncResult(ok: true);

  // ── the app blocker: an in-memory native side ──
  BlockerConfig blocker = const BlockerConfig();
  bool serviceEnabled = false;
  BlockerDecision decision = const BlockerDecision(blocked: true, code: 'tasks_left', left: 3, overdue: 2);
  List<InstalledApp> apps = const [
    InstalledApp(package: 'com.android.calculator2', label: 'Calculator'),
    InstalledApp(package: 'com.google.android.youtube', label: 'YouTube'),
    InstalledApp(package: 'com.instagram.android', label: 'Instagram'),
    InstalledApp(package: 'com.android.chrome', label: 'Chrome'),
  ];
  int accessibilityOpened = 0;
  final List<BlockerConfig> savedConfigs = [];

  @override
  Future<BlockerConfig> blockerConfig() async => blocker;
  @override
  Future<BlockerConfig> setBlockerConfig(BlockerConfig c) async {
    savedConfigs.add(c);
    return blocker = c;
  }

  @override
  Future<BlockerStatus> blockerStatus() async => BlockerStatus(
        serviceEnabled: serviceEnabled,
        enabled: blocker.enabled,
        hasData: true,
        snapshotDate: '2026-11-06',
        decision: blocker.enabled ? decision : const BlockerDecision(),
      );
  @override
  Future<List<InstalledApp>> blockerApps() async => apps;
  @override
  Future<Uint8List?> blockerAppIcon(String package) async => null;
  @override
  Future<void> openAccessibilitySettings() async => accessibilityOpened++;
}

